import type { StudioModule } from "./modules.js";

// The page a browser sees at GET /. Code (curl, fetch, other agents) still gets JSON:
// see the content negotiation in server.ts. Plain HTML + CSS, no build step, no JavaScript.
// Styles follow the Agent Studio "Schematic" look; change the tokens in :root to restyle.

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);

/** Copy-paste commands for what each module adds: [what it does, command]. */
function tryIt(id: string, origin: string): [string, string][] {
  switch (id) {
    case "gemini":
      return [["Ask Gemini through this service", `curl -X POST ${origin}/api/chat -H "Content-Type: application/json" -d '{"prompt":"Explain an API in two sentences."}'`]];
    case "paidapi":
      return [
        ["402 Payment Required, with the price", `curl -i ${origin}/premium-data`],
        ["The agent pays, within its spending limits", `curl -X POST ${origin}/api/buy`],
      ];
    case "payments":
      return [
        ["A devnet address to receive payments", "npm run keygen -- --pay-to"],
        ["Check devnet USDC balances", "npm run wallets"],
      ];
    case "spending":
      return [["The agent's budget so far", `curl ${origin}/api/buy`]];
    default:
      return [];
  }
}

export function renderLanding(modules: StudioModule[], origin: string): string {
  const has = (id: string) => modules.some((m) => m.id === id);
  const cards = modules
    .map((m) => {
      const commands = tryIt(m.id, origin);
      return `<article class="key">
        <span class="led led--${m.href ? "signal" : "ok"}"></span>
        <b>${esc(m.name)}</b>
        <p>${esc(m.summary)}</p>
        ${commands.length ? `<pre class="code">${commands.map(([what, cmd]) => `<span class="comment"># ${esc(what)}</span>\n<span class="prompt">$</span> ${esc(cmd)}`).join("\n")}</pre>` : ""}
      </article>`;
    })
    .join("\n");
  const steps = [
    ...(has("gemini") || has("payments") ? ["Copy <code>.env.example</code> to <code>.env.local</code> and fill it in. Keys stay on this server."] : []),
    ...(has("payments")
      ? ['Run <code>npm run keygen -- --pay-to</code>, then get free devnet USDC at <a href="https://faucet.circle.com">faucet.circle.com ↗</a>. No real money.']
      : []),
    "Read <code>README.md</code>: every module explains its endpoints and files.",
    "Make it yours: add endpoints as files in <code>src/routes/</code>. Each one registers itself.",
  ];

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Agent service</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,400..800&family=Martian+Mono:wght@400;500;600&display=swap">
<style>${STYLES}</style>
</head>
<body>
<header class="header"><div class="inner"><span class="wordmark"><b>AGENT SERVICE</b><span>made with Agent Studio</span></span></div></header>
<main class="page">
  <span class="eyebrow">Starter · Node.js + TypeScript</span>
  <h1 class="display">Your service<br>is running.</h1>
  <p class="lead">Generated by Superteam Agent Studio. This page is for people; code calling <code>${esc(origin)}/</code> gets the same information as JSON.</p>
  <section class="module">
    <div class="strip"><span>Endpoints</span><span><span class="led led--ok"></span> ${modules.length} ${modules.length === 1 ? "module" : "modules"}</span></div>
    <div class="body">
      ${modules.length ? `<div class="keys">${cards}</div>` : `<div class="empty">Nothing plugged in yet. Add endpoints as files in <code>src/routes/</code>.</div>`}
    </div>
  </section>
  <section class="module">
    <div class="strip"><span>Next steps</span></div>
    <div class="body"><ol class="steps">${steps.map((s, i) => `<li><span>${String(i + 1).padStart(2, "0")}</span><span>${s}</span></li>`).join("")}</ol></div>
  </section>
</main>
<footer class="footer"><div class="inner"><span>${has("payments") ? "SOLANA DEVNET · TEST MONEY ONLY" : "STARTER PROJECT"}</span><span>JSON: curl ${esc(origin)}/</span></div></footer>
</body>
</html>`;
}

