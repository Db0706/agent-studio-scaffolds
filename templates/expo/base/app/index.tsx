import { Link } from "expo-router";
import { Text } from "react-native";
import { Card, Muted, Screen } from "../components/Screen";
import { modules } from "../lib/modules";

export default function Home() {
  return (
    <Screen>
      <Text style={{ fontSize: 24, fontWeight: "700" }}>Your agent app</Text>
      <Muted>Generated by Superteam Agent Studio. Edit app/index.tsx to make it yours.</Muted>
      {modules.length === 0 ? (
        <Text>No modules included yet.</Text>
      ) : (
        modules.map((m) => (
          <Card key={m.id}>
            {m.href ? (
              <Link href={m.href} style={{ fontSize: 18, fontWeight: "600", color: "#512da8" }}>
                {m.name} →
              </Link>
            ) : (
              <Text style={{ fontSize: 18, fontWeight: "600" }}>{m.name}</Text>
            )}
            <Muted>{m.summary}</Muted>
          </Card>
        ))
      )}
    </Screen>
  );
}
