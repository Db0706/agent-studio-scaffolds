import { Link } from "expo-router";
import { useEffect, useState } from "react";
import { Pressable, Text, View } from "react-native";
import { Led, Module, PageHeader, Screen, StripStatus, colors, mono } from "../components/Screen";
import { companionFetch, companionUrl } from "../lib/companion";
import { modules } from "../lib/modules";

export default function Home() {
  return (
    <Screen>
      <PageHeader eyebrow="Starter · Expo" title={"Your app is\nrunning."}>
        Generated by Superteam Agent Studio. Everything here is yours to change: start with app/index.tsx.
      </PageHeader>

      {modules.length > 0 ? <CompanionStatus /> : null}

      <Module label="What's plugged in" right={<StripStatus tone="ok">{`${modules.length} ${modules.length === 1 ? "module" : "modules"}`}</StripStatus>}>
        {modules.length === 0 ? (
          <View style={{ borderWidth: 1.5, borderStyle: "dashed", borderColor: "#AFAFA8", borderRadius: 4, padding: 20 }}>
            <Text style={{ color: colors.muted, textAlign: "center" }}>Nothing plugged in yet. This is a clean Expo app: build anything.</Text>
          </View>
        ) : (
          modules.map((m) => (m.href ? <ModuleKey key={m.id} module={m} href={m.href} /> : <ModuleKey key={m.id} module={m} />))
        )}
      </Module>
    </Screen>
  );
}

function ModuleKey({ module: m, href }: { module: (typeof modules)[number]; href?: string }) {
  const body = (pressed: boolean) => (
    <View
      style={{
        borderWidth: 1,
        borderColor: pressed ? colors.ink : colors.rest,
        borderRadius: 4,
        padding: 12,
        gap: 6,
        backgroundColor: pressed ? colors.strip : "#FFFFFF",
      }}
    >
      <View style={{ flexDirection: "row", justifyContent: "space-between", alignItems: "center", gap: 8 }}>
        <Text style={{ fontSize: 15, fontWeight: "700", color: colors.ink, flex: 1 }}>{m.name}</Text>
        <Led tone={href ? "signal" : "ok"} size={10} />
      </View>
      <Text style={{ fontSize: 13, lineHeight: 19, color: colors.ink2 }}>{m.summary}</Text>
      {href ? <Text style={{ fontFamily: mono, fontSize: 10.5, color: colors.signal }}>OPEN ▸</Text> : null}
    </View>
  );
  if (!href) return body(false);
  return (
    <Link href={href} asChild>
      <Pressable accessibilityRole="link">{({ pressed }) => body(pressed)}</Pressable>
    </Link>
  );
}

/** Pings the companion server so you can see at a glance whether the app can reach it. */
function CompanionStatus() {
  const [state, setState] = useState<"checking" | "online" | "offline">("checking");
  const [checks, setChecks] = useState(0);

  useEffect(() => {
    let cancelled = false;
    setState("checking");
    companionFetch("/")
      .then((res) => !cancelled && setState(res.ok ? "online" : "offline"))
      .catch(() => !cancelled && setState("offline"));
    return () => {
      cancelled = true;
    };
  }, [checks]);

  const tone = state === "online" ? "ok" : state === "offline" ? "fault" : "signal";
  return (
    <Module label="Companion server" right={<StripStatus tone={tone}>{state}</StripStatus>}>
      <Text style={{ fontFamily: mono, fontSize: 12, color: colors.ink }} selectable>
        {companionUrl()}
      </Text>
      <Text style={{ fontSize: 13, lineHeight: 19, color: colors.ink2 }}>
        {state === "offline"
          ? "Not reachable. Run `npm run companion` in a second terminal, and keep your phone on the same Wi-Fi as your computer."
          : "Keys and payments live here, never in the app. The app only calls it over HTTP."}
      </Text>
      <Pressable accessibilityRole="button" onPress={() => setChecks((c) => c + 1)}>
        <Text style={{ fontFamily: mono, fontSize: 10.5, color: colors.signal }}>CHECK AGAIN ▸</Text>
      </Pressable>
    </Module>
  );
}
